"""Export one snapshot set's graph to Neo4j: as files, or straight into a database.

The files are the default and need no server: four CSVs, an `import.cypher` that
loads them with `LOAD CSV`, and a `manifest.json` naming the set, its
`gold_digest` and a digest of the files. The same set exported twice gives the
same bytes. A live export (`push()`) needs the optional `neo4j` driver.

Nodes are `:Entity` (with `:Company` or `:Person`) keyed by
(`snapshot_set_id`, `id`), so several sets can sit in one database. Edges keep
the ontology's direction (subject -> object). A designation is a
`:Designation` node that `DESIGNATES` the designated entity and `REACHES` the
entity it was matched to. Name links are `POSSIBLY_SAME`, once per pair.
Nothing reads Neo4j back: screening, determinism and replay never see it.
"""

import csv
import hashlib
import io
import json
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any

from ubo_sentinel import __version__
from ubo_sentinel.graph.export import (
    DESIGNATION_COLUMNS,
    EDGE_COLUMNS,
    LINK_COLUMNS,
    NODE_COLUMNS,
    GraphRows,
)

# A list property (aliases) in one CSV cell: the ASCII unit separator, which no
# name holds; `import.cypher` splits on it.
LIST_SEPARATOR = "\x1f"
FILES = ("nodes.csv", "relationships.csv", "designations.csv", "links.csv")
BATCH = 5000

_RELATIONS = ("OWNS", "CONSOLIDATED_BY", "CONTROLS")
_NODE_LABELS = {"LegalEntity": "Company", "Person": "Person"}


def _cell(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return LIST_SEPARATOR.join(str(item) for item in value)
    return str(value)


def _csv(columns: tuple[str, ...], rows: Iterable[dict[str, Any]], set_id: str) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(("snapshot_set_id", *columns))
    for row in rows:
        writer.writerow((set_id, *(_cell(row.get(column)) for column in columns)))
    return buffer.getvalue().encode("utf-8")


def _node_props(var: str) -> str:
    props = [c for c in NODE_COLUMNS if c not in ("id", "aliases")]
    sets = ", ".join(f"{var}.{c} = nullif(row.{c}, '')" for c in props)
    return (
        f"SET {sets}, {var}.aliases = CASE row.aliases WHEN '' THEN [] ELSE"
        f" split(row.aliases, '{LIST_SEPARATOR}') END,"
        f" {var}.confidence = toFloat(row.confidence), {var}.as_of = date(row.as_of)"
    )


def import_cypher() -> str:
    """Statements that load the four CSVs from Neo4j's import directory. Run with
    `cypher-shell -f import.cypher` (implicit transactions, for `IN TRANSACTIONS`)."""
    every = f"IN TRANSACTIONS OF {BATCH} ROWS"
    edge_sets = (
        "SET r.id = row.id, r.upper_id = row.upper_id, r.lower_id = row.lower_id,"
        " r.pct = toFloat(nullif(row.pct, '')), r.pct_text = nullif(row.pct, ''),"
        " r.basis = row.basis, r.is_ultimate = row.is_ultimate = 'true',"
        " r.source = row.source, r.source_record_id = row.source_record_id,"
        " r.snapshot_id = row.snapshot_id, r.as_of = date(row.as_of),"
        " r.confidence = toFloat(row.confidence)"
    )
    statements = [
        "// Generated by ubo-sentinel (ubo export neo4j). Loads one snapshot set.",
        "CREATE CONSTRAINT ubo_entity_key IF NOT EXISTS FOR (n:Entity)"
        " REQUIRE (n.snapshot_set_id, n.id) IS UNIQUE;",
        "CREATE CONSTRAINT ubo_designation_key IF NOT EXISTS FOR (d:Designation)"
        " REQUIRE (d.snapshot_set_id, d.id) IS UNIQUE;",
        "LOAD CSV WITH HEADERS FROM 'file:///nodes.csv' AS row CALL { WITH row"
        " MERGE (n:Entity {snapshot_set_id: row.snapshot_set_id, id: row.id})"
        f" {_node_props('n')}"
        " FOREACH (_ IN CASE WHEN row.label = 'Person' THEN [1] ELSE [] END | SET n:Person)"
        " FOREACH (_ IN CASE WHEN row.label = 'LegalEntity' THEN [1] ELSE [] END"
        f" | SET n:Company) }} {every};",
    ]
    for relation in _RELATIONS:
        statements.append(
            "LOAD CSV WITH HEADERS FROM 'file:///relationships.csv' AS row"
            f" WITH row WHERE row.rel_type = '{relation}' CALL {{ WITH row"
            " MATCH (s:Entity {snapshot_set_id: row.snapshot_set_id, id: row.subject_id})"
            " MATCH (o:Entity {snapshot_set_id: row.snapshot_set_id, id: row.object_id})"
            f" MERGE (s)-[r:{relation} {{snapshot_set_id: row.snapshot_set_id, id: row.id}}]->(o)"
            f" {edge_sets} }} {every};"
        )
    statements += [
        "LOAD CSV WITH HEADERS FROM 'file:///designations.csv' AS row CALL { WITH row"
        " MERGE (d:Designation {snapshot_set_id: row.snapshot_set_id, id: row.id})"
        " SET d.program = row.program, d.list_date = date(nullif(row.list_date, '')),"
        " d.list_source = row.list_source, d.is_active = row.is_active = 'true',"
        " d.source = row.source, d.source_record_id = row.source_record_id,"
        " d.snapshot_id = row.snapshot_id, d.as_of = date(row.as_of)"
        " WITH d, row"
        " MATCH (x:Entity {snapshot_set_id: row.snapshot_set_id, id: row.designated_entity_id})"
        " MATCH (e:Entity {snapshot_set_id: row.snapshot_set_id, id: row.entity_id})"
        " MERGE (d)-[:DESIGNATES]->(x)"
        " MERGE (d)-[m:REACHES]->(e)"
        " SET m.match_type = row.match_type,"
        f" m.match_confidence = toFloat(row.match_confidence) }} {every};",
        "LOAD CSV WITH HEADERS FROM 'file:///links.csv' AS row CALL { WITH row"
        " MATCH (a:Entity {snapshot_set_id: row.snapshot_set_id, id: row.node_id})"
        " MATCH (b:Entity {snapshot_set_id: row.snapshot_set_id, id: row.linked_node_id})"
        " MERGE (a)-[l:POSSIBLY_SAME]->(b)"
        f" SET l.match_type = row.match_type, l.confidence = toFloat(row.confidence) }} {every};",
    ]
    return "\n".join(statements) + "\n"


def render(rows: GraphRows) -> dict[str, bytes]:
    """File name -> bytes, the manifest included."""
    set_id = rows.snapshot_set_id
    files = {
        "nodes.csv": _csv(NODE_COLUMNS, rows.nodes, set_id),
        "relationships.csv": _csv(EDGE_COLUMNS, rows.edges, set_id),
        "designations.csv": _csv(DESIGNATION_COLUMNS, rows.designations, set_id),
        "links.csv": _csv(LINK_COLUMNS, rows.links, set_id),
        "import.cypher": import_cypher().encode("utf-8"),
    }
    digest = hashlib.sha256()
    for name in sorted(files):
        digest.update(name.encode("utf-8") + b"\0" + hashlib.sha256(files[name]).digest())
    manifest = {
        "snapshot_set_id": set_id,
        "gold_digest": rows.gold_digest,
        "engine_version": __version__,
        "role": rows.role,
        "masked": rows.masked,
        "counts": rows.counts(),
        "files": {name: hashlib.sha256(files[name]).hexdigest() for name in sorted(files)},
        "export_digest": digest.hexdigest(),
    }
    files["manifest.json"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return files


def write(rows: GraphRows, out: Path) -> dict[str, Any]:
    """Write the export into `out` (created if missing) and return its manifest."""
    out.mkdir(parents=True, exist_ok=True)
    files = render(rows)
    for name, data in files.items():
        (out / name).write_bytes(data)
    return json.loads(files["manifest.json"])


# --- live export -------------------------------------------------------------------------


def _batches(items: list[dict[str, Any]]) -> Iterable[list[dict[str, Any]]]:
    for start in range(0, len(items), BATCH):
        yield items[start : start + BATCH]


def _params(rows: GraphRows) -> dict[str, list[dict[str, Any]]]:
    """Rows as driver parameters: numbers as numbers, the percentage also as exact text."""

    def num(value: Any) -> float | None:
        return None if value in (None, "") else float(value)

    return {
        "nodes": [
            {k: row[k] for k in NODE_COLUMNS} | {"confidence": num(row["confidence"])}
            for row in rows.nodes
        ],
        "edges": [
            {k: row[k] for k in EDGE_COLUMNS}
            | {"pct": num(row["pct"]), "pct_text": row["pct"], "confidence": num(row["confidence"])}
            for row in rows.edges
        ],
        "designations": [
            {k: row[k] for k in DESIGNATION_COLUMNS}
            | {"match_confidence": num(row["match_confidence"])}
            for row in rows.designations
        ],
        "links": [
            {k: row[k] for k in LINK_COLUMNS} | {"confidence": num(row["confidence"])}
            for row in rows.links
        ],
    }


def _live_queries() -> dict[str, str]:
    node_props = ", ".join(f"n.{c} = row.{c}" for c in NODE_COLUMNS if c not in ("id",))
    edge_props = ", ".join(
        f"r.{c} = row.{c}" for c in (*EDGE_COLUMNS, "pct_text") if c not in ("rel_type",)
    )
    queries = {
        "nodes": "UNWIND $rows AS row MERGE (n:Entity {snapshot_set_id: $set, id: row.id})"
        f" SET {node_props}"
        " FOREACH (_ IN CASE WHEN row.label = 'Person' THEN [1] ELSE [] END | SET n:Person)"
        " FOREACH (_ IN CASE WHEN row.label = 'LegalEntity' THEN [1] ELSE [] END | SET n:Company)",
        "designations": "UNWIND $rows AS row"
        " MERGE (d:Designation {snapshot_set_id: $set, id: row.id})"
        " SET d.program = row.program, d.list_date = row.list_date,"
        " d.list_source = row.list_source, d.is_active = row.is_active,"
        " d.source = row.source, d.source_record_id = row.source_record_id,"
        " d.snapshot_id = row.snapshot_id, d.as_of = row.as_of WITH d, row"
        " MATCH (x:Entity {snapshot_set_id: $set, id: row.designated_entity_id})"
        " MATCH (e:Entity {snapshot_set_id: $set, id: row.entity_id})"
        " MERGE (d)-[:DESIGNATES]->(x) MERGE (d)-[m:REACHES]->(e)"
        " SET m.match_type = row.match_type, m.match_confidence = row.match_confidence",
        "links": "UNWIND $rows AS row"
        " MATCH (a:Entity {snapshot_set_id: $set, id: row.node_id})"
        " MATCH (b:Entity {snapshot_set_id: $set, id: row.linked_node_id})"
        " MERGE (a)-[l:POSSIBLY_SAME]->(b)"
        " SET l.match_type = row.match_type, l.confidence = row.confidence",
    }
    for relation in _RELATIONS:
        queries[relation] = (
            f"UNWIND [row IN $rows WHERE row.rel_type = '{relation}'] AS row"
            " MATCH (s:Entity {snapshot_set_id: $set, id: row.subject_id})"
            " MATCH (o:Entity {snapshot_set_id: $set, id: row.object_id})"
            f" MERGE (s)-[r:{relation} {{snapshot_set_id: $set, id: row.id}}]->(o)"
            f" SET {edge_props}"
        )
    return queries


CONSTRAINTS = (
    "CREATE CONSTRAINT ubo_entity_key IF NOT EXISTS FOR (n:Entity)"
    " REQUIRE (n.snapshot_set_id, n.id) IS UNIQUE",
    "CREATE CONSTRAINT ubo_designation_key IF NOT EXISTS FOR (d:Designation)"
    " REQUIRE (d.snapshot_set_id, d.id) IS UNIQUE",
)
DELETE_SET = (
    "MATCH (n {snapshot_set_id: $set}) WHERE n:Entity OR n:Designation"
    f" CALL {{ WITH n DETACH DELETE n }} IN TRANSACTIONS OF {BATCH} ROWS"
)


def push(
    rows: GraphRows,
    uri: str,
    auth: tuple[str, str] | None,
    replace: bool = False,
    driver_factory: Callable[..., Any] | None = None,
) -> dict[str, int]:
    """Load the rows into a Neo4j database, idempotently (MERGE on the keys).

    `replace` first deletes what the database holds of this set. Raises
    `ImportError` when the driver is not installed (`uv sync --extra optional`).
    """
    if driver_factory is None:
        from neo4j import GraphDatabase

        driver_factory = GraphDatabase.driver
    params = _params(rows)
    queries = _live_queries()
    set_id = rows.snapshot_set_id
    with driver_factory(uri, auth=auth) as driver, driver.session() as session:
        for statement in CONSTRAINTS:
            session.run(statement)
        if replace:
            # `IN TRANSACTIONS` needs an implicit transaction: `session.run`.
            session.run(DELETE_SET, set=set_id)
        for key, query_key in (("nodes", "nodes"), *(("edges", r) for r in _RELATIONS),
                               ("designations", "designations"), ("links", "links")):  # fmt: skip
            for batch in _batches(params[key]):
                session.execute_write(
                    lambda tx, q=queries[query_key], b=batch: tx.run(
                        q, rows=b, set=set_id
                    ).consume()
                )
    return rows.counts()
